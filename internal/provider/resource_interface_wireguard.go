func (r *InterfaceWireguardResource) ImportState(ctx context.Context, req resource.ImportStateRequest, resp *resource.ImportStateResponse) {
	// Import formats accepted:
	//   *<id>                            -> bare RouterOS .id on the default router
	//   <router>/*<id>                   -> .id on the named router
	//   <router>/<naturalkey>            -> resolved via List + filter
	//   <naturalkey>                     -> resolved on the default router
	routerName, id := parseImportID(r.reg, req.ID)
	resp.Diagnostics.Append(resp.State.SetAttribute(ctx, path.Root("router"), types.StringValue(routerName))...)
	if strings.HasPrefix(id, "*") {
		resp.Diagnostics.Append(resp.State.SetAttribute(ctx, path.Root("id"), types.StringValue(id))...)
		return
	}
	c := pickClient(r.reg, types.StringValue(routerName), &resp.Diagnostics)
	if c == nil {
		return
	}
	rows, err := interfaceWireguardLookupByNaturalKey(ctx, c, id)
	if err != nil {
		resp.Diagnostics.AddError("Import lookup failed", err.Error())
		return
	}
	if len(rows) == 0 {
		resp.Diagnostics.AddError("Import not found", fmt.Sprintf("no /interface/wireguard matches %q", id))
		return
	}
	resp.Diagnostics.Append(resp.State.SetAttribute(ctx, path.Root("id"), types.StringValue(rows[0][".id"]))...)
}

// interfaceWireguardLookupByNaturalKey searches for a record whose natural
// keys match id. The strategy: try every key declared in the schema overlay's
// natural_keys list (or fall back to "name") with equality matching.
func interfaceWireguardLookupByNaturalKey(ctx context.Context, c *client.Client, id string) ([]client.Object, error) {
	return lookupByNaturalKey(ctx, c, "/interface/wireguard", id)
}

func interfaceWireguardApply(ctx context.Context, obj client.Object, m *InterfaceWireguardModel) {
	_ = ctx
	m.ID = types.StringValue(obj[".id"])
	if v, ok := obj["vrf"]; ok && v != "" {
		m.Vrf = types.StringValue(v)
	} else {
		m.Vrf = types.StringNull()
	}
	if v, ok := obj["comment"]; ok {
		_ = v
		if v != "" {
			m.Comment = types.StringValue(v)
		} else {
			m.Comment = types.StringNull()
		}
	} else {
		m.Comment = types.StringNull()
	}
	if v, ok := obj["disabled"]; ok {
		if b, err := client.ParseBool(v); err == nil {
			m.Disabled = types.BoolValue(b)
		} else {
			m.Disabled = types.BoolNull()
		}
	}
	if v, ok := obj["listen-port"]; ok {
		_ = v
		if n, err := client.ParseInt64(v); err == nil {
			m.ListenPort = types.Int64Value(n)
		} else {
			m.ListenPort = types.Int64Null()
		}
	} else {
		m.ListenPort = types.Int64Null()
	}
	if v, ok := obj["mtu"]; ok {
		_ = v
		if v != "" {
			m.MTU = types.StringValue(v)
		} else {
			m.MTU = types.StringNull()
		}
	} else {
		m.MTU = types.StringNull()
	}
	if v, ok := obj["name"]; ok {
		_ = v
		if v != "" {
			m.Name = types.StringValue(v)
		} else {
			m.Name = types.StringNull()
		}
	} else {
		m.Name = types.StringNull()
	}
	// Sensitive: RouterOS scrubs the value on read. If the server returned
	// a value, decode it. Otherwise the plan value (user input) is what's
	// in m.PrivateKey already -- but if the user left it unset, resolve
	// the unknown to null so the framework accepts the state.
	if v, ok := obj["private-key"]; ok && v != "" {
		_ = v
		if v != "" {
			m.PrivateKey = types.StringValue(v)
		} else {
			m.PrivateKey = types.StringNull()
		}
	} else if m.PrivateKey.IsUnknown() {
		m.PrivateKey = types.StringNull()
	}
	if v, ok := obj["public-key"]; ok {
		_ = v
		if v != "" {
			m.PublicKey = types.StringValue(v)
		} else {
			m.PublicKey = types.StringNull()
		}
	} else {
		m.PublicKey = types.StringNull()
	}
	if v, ok := obj["wg-export"]; ok {
		_ = v
		if v != "" {
			m.WgExport = types.StringValue(v)
		} else {
			m.WgExport = types.StringNull()
		}
	} else {
		m.WgExport = types.StringNull()
	}
}
